def coverage_blocks(payload, coverage_geo, geo):
    """Compact the LGU coverage geometry + per-utility service areas for inlining.

    The page needs three things the API payload does not carry:
      * the geometry of every city/municipality (paths + names, province index);
      * each utility's covered LGU indexes (small ints, not 10-char PSGC strings);
      * the service-area source registry + stats for the credit lines.
    """
    region_order = {r["psgc"]: i for i, r in enumerate(payload["regions"])}
    province_items = sorted(
        coverage_geo["provinces"].items(),
        key=lambda item: (region_order.get(item[1]["region_psgc"], 99), item[0]))
    province_index = {psgc: i for i, (psgc, _item) in enumerate(province_items)}
    provinces = [
        {"psgc": psgc, "n": item["name"], "r": item["region_psgc"]}
        for psgc, item in province_items
    ]
    totals = [0] * len(provinces)
    names, province_of, paths = [], [], []
    lgu_index = {}
    for psgc, lgu in sorted(coverage_geo["lgus"].items()):
        index = province_index[lgu["province_psgc"]]
        lgu_index[psgc] = len(names)
        names.append(lgu["name"])
        province_of.append(index)
        paths.append(lgu["path"])
        totals[index] += 1
    coverage = {}
    for utility in payload["utilities"]:
        item = utility["coverage"]
        indexes = [lgu_index[psgc] for psgc in item["lgus"] if psgc in lgu_index]
        coverage[utility["code"]] = {
            "d": item["detail"],
            "r": item["regions"],
            "l": indexes,
            "b": item["barangay_count"],
            "bp": item.get("barangay_provinces", []),
            "bl": sorted({barangay["lgu_name"] for barangay in item.get("barangays", [])}),
            "nt": item.get("note", ""),
            "s": item["source_ids"],
        }
    sources = {}
    for source in payload["coverage"]["sources"]:
        sources[source["source_id"]] = {
            "publisher": source["publisher"],
            "title": source["dataset_title"],
            "url": source["page_url"],
            "license": source["license"],
            "attribution": source["attribution"],
            "notes": source["notes"],
        }
    lgu_block = {
        "w": coverage_geo["width"],
        "h": coverage_geo["height"],
        "provinces": provinces,
        "names": names,
        "prov": province_of,
        "paths": paths,
        "totals": totals,
        "regions": [
            {"psgc": code, "short": region["short"],
             "x": region["label_x"], "y": region["label_y"]}
            for code, region in geo["regions"].items()
        ],
    }
    return lgu_block, coverage, sources, payload["coverage"]["stats"]


