def _api_groups(payload):
    catalog = payload.get("_api_catalog") or {}
    endpoints = catalog.get("endpoints") or []
    if endpoints:
        groups = {}
        for ep in endpoints:
            groups.setdefault(ep.get("tag") or "API", []).append(
                (ep.get("method", "GET"), ep.get("path", ""), ep.get("summary", ""), ep.get("file", "")))
        return [(tag.replace("-", " ").title(), items) for tag, items in groups.items()]
    return FALLBACK_API_GROUPS


