def dropdown(dd_id, label_id, options, value, extra_class="", searchable=False,
             dynamic=False, search_placeholder="Search options\u2026"):
    """Accessible custom listbox dropdown. `options` = [(value, label[, meta]), ...].

    `searchable` adds a filter input at the top of the popover; `dynamic` marks a
    listbox whose real options are appended by the page script from the dataset
    (used for the 141-provider lists so the HTML stays small).
    """
    if dynamic:
        options = []
    current = next((o[1] for o in options if str(o[0]) == str(value)),
                   options[0][1] if options else "All providers")
    items = []
    for i, opt in enumerate(options):
        val, lab = opt[0], opt[1]
        meta = opt[2] if len(opt) > 2 else ""
        selected = "true" if str(val) == str(value) else "false"
        meta_html = f'<span class="dd-meta">{esc(meta)}</span>' if meta else ""
        items.append(
            f'<li class="dd-opt" role="option" id="{dd_id}-opt-{i}" data-value="{esc_attr(val)}" '
            f'aria-selected="{selected}"><span class="dd-opt-label">{esc(lab)}</span>{meta_html}'
            f'<span class="dd-check">{icon("check")}</span></li>')
    search_html = ""
    if searchable:
        search_html = (
            f'<div class="dd-search"><input type="search" id="{dd_id}-search" '
            f'placeholder="{esc_attr(search_placeholder)}" aria-label="Filter options" '
            'autocomplete="off" spellcheck="false"></div>')
    root_attrs = f' data-dd id="{dd_id}-dd"'
    if dynamic:
        root_attrs += ' data-dynamic="providers"'
    return (f'<div class="dd {extra_class}"{root_attrs}>'
            f'<input type="hidden" id="{dd_id}" value="{esc_attr(value)}">'
            f'<button type="button" class="dd-btn" id="{dd_id}-btn" aria-haspopup="listbox" '
            f'aria-expanded="false" aria-controls="{dd_id}-list" '
            f'aria-labelledby="{label_id} {dd_id}-btn">'
            f'<span class="dd-value">{esc(current)}</span>{icon("chevron-down")}</button>'
            f'<div class="dd-pop" id="{dd_id}-pop">{search_html}'
            f'<ul class="dd-menu" id="{dd_id}-list" role="listbox" tabindex="-1">'
            f'{"".join(items)}</ul></div></div>')


def field(label, dd_id, options, value, grow=False, searchable=False, dynamic=False,
          css_class="", search_placeholder="Search options\u2026"):
    cls = "field"
    if grow:
        cls += " field-grow"
    if css_class:
        cls += " " + css_class
    dd_html = dropdown(dd_id, f"{dd_id}-label", options, value,
                       searchable=searchable, dynamic=dynamic,
                       search_placeholder=search_placeholder)
    return (f'<div class="{cls}"><span class="label" id="{dd_id}-label">{esc(label)}</span>'
            f'{dd_html}</div>')


def switch(sw_id, label, checked):
    state = "true" if checked else "false"
    return (f'<button type="button" class="switch" id="{sw_id}" role="switch" aria-checked="{state}">'
            f'<span class="switch-track" aria-hidden="true"><span class="switch-thumb"></span></span>'
            f'<span class="switch-label">{esc(label)}</span></button>')


def trim_example(obj, limit=5):
    """Trim a static-API response for the in-page explorer; return (payload, note)."""
    note = ""
    data = obj.get("data")
    if isinstance(data, list) and len(data) > limit:
        note = f"showing {limit} of {len(data)} rows"
        obj = dict(obj)
        obj["data"] = data[:limit]
    elif isinstance(data, dict):
        for key, val in list(data.items()):
            if isinstance(val, list) and len(val) > limit:
                note = note or f"showing {limit} of {len(val)} {key.replace('_', ' ')}"
                obj = json.loads(json.dumps(obj))
                obj["data"][key] = val[:limit]
                break
    return obj, note


def load_api_explorer():
    """Load real static-API responses for the page's API section.

    Reads draft/api/v1/* (generated by tools/build-api.py). Every tab maps to a
    real file so the page never shows an invented response.
    """
    specs = [
        ("health", "GET", "/v1/health", "Health", "api/v1/health.json"),
        ("rates", "GET", "/v1/rates/latest/residential", "Latest residential rates", "api/v1/rates/latest/residential.json"),
        ("utilities", "GET", "/v1/utilities", "Utilities", "api/v1/utilities.json"),
        ("region", "GET", "/v1/regions/0700000000", "One region", "api/v1/regions/0700000000.json"),
        ("changes", "GET", "/v1/changes/latest", "Change feed", "api/v1/changes/latest.json"),
        ("source", "GET", "/v1/sources/SRC-DOE-RATES", "Source record", "api/v1/sources/SRC-DOE-RATES.json"),
    ]
    tabs, catalog = [], {}
    idx_path = os.path.join(ROOT, "draft", "api", "v1", "index.json")
    if os.path.exists(idx_path):
        try:
            catalog = json.loads(read_text(idx_path))
        except (ValueError, OSError):
            catalog = {}
    for key, method, path, label, rel in specs:
        full = os.path.join(ROOT, "draft", rel)
        if not os.path.exists(full):
            continue
        try:
            raw = json.loads(read_text(full))
        except (ValueError, OSError):
            continue
        payload, note = trim_example(raw)
        tabs.append({"key": key, "method": method, "path": path, "label": label,
                     "file": rel, "payload": payload, "note": note,
                     "size": os.path.getsize(full)})
    return tabs, catalog


