def load_icons():
    """Interface icons. Sourced from draft/assets/brand/icons.json when present."""
    path = os.path.join(ASSETS, "brand", "icons.json")
    if os.path.exists(path):
        try:
            data = json.loads(read_text(path))
            ICONS.update(data.get("icons") or {})
        except (ValueError, OSError):
            pass


def icon(name, cls="i", label=None):
    body = ICONS.get(name) or ICON_FALLBACK.get(name) or ""
    if isinstance(body, dict):
        body = body.get("body", "")
    aria = f' aria-label="{esc_attr(label)}" role="img"' if label else ' aria-hidden="true" focusable="false"'
    return (f'<svg class="{cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor" '
            f'stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"{aria}>{body}</svg>')


def load_emblem():
    """Official BetterGov.ph emblem, inlined from draft/assets/brand/emblem.svg."""
    global EMBLEM
    path = os.path.join(ASSETS, "brand", "emblem.svg")
    if not os.path.exists(path):
        EMBLEM = ""
        return
    src = read_text(path).strip()
    src = re.sub(r"<\?xml[^>]*\?>", "", src).strip()
    src = re.sub(r"<!--.*?-->", "", src, flags=re.S).strip()
    src = src.replace("<svg ", '<svg class="emblem" aria-hidden="true" focusable="false" ', 1)
    EMBLEM = src


